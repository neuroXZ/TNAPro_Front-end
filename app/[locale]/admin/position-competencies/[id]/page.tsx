"use client"

import { useState, useEffect, useRef } from "react"
import { useParams, useRouter } from "next/navigation"
import { positionAPI, competencyAPI, positionCompetencyAPI, unitAPI, mappingTemplateAPI, templateLevelFor, type TemplateRuleInput } from "@/lib/api"
import { useFeatureFlags } from "@/hooks/use-feature-flags"
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card"
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs"
import { Button } from "@/components/ui/button"
import { Badge } from "@/components/ui/badge"
import { IconArrowLeft, IconPlus, IconEdit, IconTrash, IconEye, IconTrashX, IconSearch, IconAlertTriangle, IconBuilding, IconRestore, IconInfoCircle } from "@tabler/icons-react"
import { toast } from "sonner"
import { Skeleton } from "@/components/ui/skeleton"
import { Checkbox } from "@/components/ui/checkbox"
import { Input } from "@/components/ui/input"
import {
  Command,
  CommandEmpty,
  CommandGroup,
  CommandInput,
  CommandItem,
  CommandList,
} from "@/components/ui/command"
import {
  Popover,
  PopoverContent,
  PopoverTrigger,
} from "@/components/ui/popover"
import { CompetencyLevelDialog } from "@/features/admin/position-competencies/[id]/components/competency-level-dialog"
import { CompetencyViewDialog } from "@/features/admin/position-competencies/[id]/components/competency-view-dialog"
import { CompetencyDeleteDialog } from "@/features/admin/position-competencies/[id]/components/competency-delete-dialog"
import { BulkLevelDialog } from "@/features/admin/position-competencies/[id]/components/bulk-level-dialog"
import { useTranslations } from "next-intl"
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert"
import { summarizePositionScopes, type ScopeSummary } from "@/features/admin/position-competencies/lib/scope-summary"

interface Position {
  id: string
  name: string
  categoryId?: string | null
  grade?: { name: string }
}

interface Cluster {
  id: string
  name: string
  color?: string
}

interface Competency {
  id: string
  name: string
  description?: string
  clusterId?: string
  cluster?: Cluster
}

interface Unit {
  id: string
  name: string
  parentId?: string | null
}

interface PositionCompetency {
  id: string
  positionId: string
  competencyId: string
  unitId?: string | null
  unit?: Unit | null
  level: number
  // MANUAL = set by admin/import; TEMPLATE = generated by the base mapping template.
  source?: "MANUAL" | "TEMPLATE"
  competency: Competency
}

interface GroupedCompetencies {
  [clusterId: string]: {
    cluster: Cluster | null
    competencies: Array<{
      competency: Competency
      positionCompetency?: PositionCompetency
    }>
  }
}

// Sentinel for the unit-scope selector's "All Scopes" option — an aggregate,
// read-only view across Global + every unit, matching the raw count the
// listing page shows. Never sent to the API as a real unitId (Add/bulk-add
// are disabled while this is selected — a new mapping needs one concrete
// target scope, either Global or a specific unit).
const ALL_SCOPES = "__all__"

export default function PositionCompetencyDetailPage() {
  const t = useTranslations('AdminPositionCompetenciesDetailPage')
  const params = useParams()
  const router = useRouter()
  const positionId = params.id as string
  const { flags: featureFlags } = useFeatureFlags()

  const [position, setPosition] = useState<Position | null>(null)
  const [allCompetencies, setAllCompetencies] = useState<Competency[]>([])
  const [positionCompetencies, setPositionCompetencies] = useState<PositionCompetency[]>([])
  const [isLoading, setIsLoading] = useState(true)

  // Unit scope: null = Global (org-wide) mappings, matching every client's
  // existing data. Only relevant when unitScopedCompetency is on.
  const [units, setUnits] = useState<Unit[]>([])
  const [selectedUnitId, setSelectedUnitId] = useState<string | null>(null)
  const [unitScopePopoverOpen, setUnitScopePopoverOpen] = useState(false)

  // Dialog states
  const [isLevelDialogOpen, setIsLevelDialogOpen] = useState(false)
  const [isViewDialogOpen, setIsViewDialogOpen] = useState(false)
  const [isDeleteDialogOpen, setIsDeleteDialogOpen] = useState(false)
  const [selectedCompetency, setSelectedCompetency] = useState<Competency | null>(null)
  const [selectedPositionCompetency, setSelectedPositionCompetency] = useState<PositionCompetency | null>(null)
  const [editMode, setEditMode] = useState(false)
  const [selectedIds, setSelectedIds] = useState<string[]>([])
  const [selectedCompetencyIds, setSelectedCompetencyIds] = useState<string[]>([])
  const [isBulkDeleting, setIsBulkDeleting] = useState(false)
  const [isRemovingOrphaned, setIsRemovingOrphaned] = useState(false)
  const [isBulkAdding, setIsBulkAdding] = useState(false)
  const [activeTab, setActiveTab] = useState<string>("")
  const [searchQuery, setSearchQuery] = useState("")
  const [isBulkLevelDialogOpen, setIsBulkLevelDialogOpen] = useState(false)

  // Base mapping template (docs/MAPPING_TEMPLATE_PLAN.md §6). Empty on
  // deployments without a template, in which case nothing below changes.
  const [templateRules, setTemplateRules] = useState<TemplateRuleInput[]>([])
  const [excludedCompetencyIds, setExcludedCompetencyIds] = useState<Set<string>>(new Set())
  const [resettingCompetencyId, setResettingCompetencyId] = useState<string | null>(null)

  useEffect(() => {
    fetchData()
  }, [positionId, selectedUnitId])

  // Fetched separately from fetchData() so switching feature flags on/off
  // never affects the competency-list fetch above.
  useEffect(() => {
    if (!featureFlags.unitScopedCompetency) return
    unitAPI.getAll().then(setUnits).catch(() => {
      // Scope selector just shows no options - non-fatal, matches how
      // unit-form-dialog.tsx treats a failed negeriAPI.getAll().
    })
    // Opens on Global (the initial null), not "All Scopes": the aggregate
    // adds up every unit's own list (360 for one Waqaf Annur position) and
    // read as "staff answer 360". The listing page now shows the split and
    // the per-staff count instead of the raw total, so nothing needs the
    // two pages' first numbers to match any more.
  }, [featureFlags.unitScopedCompetency])

  // What a staff member in the selected unit is actually assessed on — the
  // same resolver the staff assessment form uses. Refetched when this
  // page's own rows change, so it stays right after an add/edit/delete.
  const [unitEffective, setUnitEffective] = useState<{ total: number; global: number; scoped: number } | null>(null)
  useEffect(() => {
    if (!selectedUnitId || selectedUnitId === ALL_SCOPES) {
      setUnitEffective(null)
      return
    }
    let cancelled = false
    positionCompetencyAPI.getEffective(positionId, selectedUnitId)
      .then((rows: Array<{ unitId?: string | null }>) => {
        if (cancelled) return
        const global = rows.filter((r) => !r.unitId).length
        setUnitEffective({ total: rows.length, global, scoped: rows.length - global })
      })
      .catch(() => {
        if (!cancelled) setUnitEffective(null) // notice just doesn't show
      })
    return () => {
      cancelled = true
    }
  }, [positionId, selectedUnitId, positionCompetencies])

  // Global/unit split for this position across every scope, whatever scope
  // is selected (the Global view's own rows can't tell whether unit lists
  // exist). Null when the position has no unit-scoped rows, which hides
  // both notices below for every client that doesn't use unit scoping.
  const [scopeSummary, setScopeSummary] = useState<ScopeSummary | null>(null)
  useEffect(() => {
    if (!featureFlags.unitScopedCompetency) return
    let cancelled = false
    positionCompetencyAPI.getByPosition(positionId)
      .then((rows) => {
        if (!cancelled) setScopeSummary(summarizePositionScopes(rows, units))
      })
      .catch(() => {
        if (!cancelled) setScopeSummary(null)
      })
    return () => {
      cancelled = true
    }
  }, [featureFlags.unitScopedCompetency, positionId, units, positionCompetencies])

  const perStaffRange = scopeSummary
    ? scopeSummary.perStaffMin === scopeSummary.perStaffMax
      ? String(scopeSummary.perStaffMin)
      : `${scopeSummary.perStaffMin}–${scopeSummary.perStaffMax}`
    : ''

  // Set initial active tab after data loads: the first cluster that has
  // something mapped in this scope, so the page doesn't open on an all-
  // "Not Added" list (e.g. Global opening on Fungsian 0/347 at Waqaf Annur).
  // Also re-picked once after a scope switch (Global's mapped cluster is
  // Teras, a unit's is Fungsian), but not after an add/edit/delete refetch -
  // that would yank the admin off the tab they're working in.
  const repickTabRef = useRef(false)
  useEffect(() => {
    repickTabRef.current = true
  }, [selectedUnitId])
  useEffect(() => {
    const grouped = groupCompetenciesByCluster()
    const groupedKeys = Object.keys(grouped)
    if ((!activeTab || repickTabRef.current) && groupedKeys.length > 0 && !isLoading) {
      repickTabRef.current = false
      const firstMapped = groupedKeys.find((k) => grouped[k].competencies.some((c) => c.positionCompetency))
      setActiveTab(firstMapped ?? groupedKeys[0])
    }
  }, [positionCompetencies, allCompetencies, isLoading])

  const fetchData = async () => {
    try {
      setIsLoading(true)
      // Selections reference this scope's own mapping ids - stale once the
      // scope changes underneath them.
      setSelectedIds([])
      setSelectedCompetencyIds([])
      const [positionData, competenciesData, positionCompetenciesData] = await Promise.all([
        positionAPI.getById(positionId),
        competencyAPI.getAll(),
        selectedUnitId === ALL_SCOPES
          ? positionCompetencyAPI.getByPosition(positionId)
          : positionCompetencyAPI.getByPositionAndUnit(positionId, selectedUnitId),
      ])
      setPosition(positionData)
      setAllCompetencies(competenciesData)
      setPositionCompetencies(positionCompetenciesData)
      // Non-fatal: without template data the page just shows no template badges.
      Promise.all([mappingTemplateAPI.get(), mappingTemplateAPI.exclusions()])
        .then(([template, exclusions]) => {
          setTemplateRules(template.rules)
          setExcludedCompetencyIds(new Set(exclusions.filter((e) => e.positionId === positionId).map((e) => e.competencyId)))
        })
        .catch((error) => console.error("Failed to load the mapping template:", error))
    } catch (error) {
      toast.error(t('fetchError'))
      console.error(error)
    } finally {
      setIsLoading(false)
    }
  }

  const groupCompetenciesByCluster = (): GroupedCompetencies => {
    const grouped: GroupedCompetencies = {}

    allCompetencies.forEach((competency) => {
      const clusterId = competency.clusterId || "uncategorized"
      
      if (!grouped[clusterId]) {
        grouped[clusterId] = {
          cluster: competency.cluster || null,
          competencies: [],
        }
      }

      // In "All Scopes" mode more than one row can match the same
      // competency (Global + one or more units) — prefer the unit-scoped
      // one, matching how the effective-mapping resolver treats a unit
      // override as taking precedence over the org-wide default. Outside
      // "All Scopes" the fetch already only contains the one selected
      // scope's rows, so this is equivalent to the old exact-match find.
      const matches = positionCompetencies.filter(
        (pc) => pc.competencyId === competency.id
      )
      const positionComp = matches.find((pc) => pc.unitId) || matches[0]

      // Filter by search query
      const matchesSearch = !searchQuery || 
        competency.name.toLowerCase().includes(searchQuery.toLowerCase())

      if (matchesSearch) {
        grouped[clusterId].competencies.push({
          competency,
          positionCompetency: positionComp,
        })
      }
    })

    // Remove empty clusters
    Object.keys(grouped).forEach((clusterId) => {
      if (grouped[clusterId].competencies.length === 0) {
        delete grouped[clusterId]
      }
    })

    return grouped
  }

  const templateFor = (competency: Competency | null | undefined) =>
    templateLevelFor(templateRules, competency?.clusterId, position?.categoryId)

  // Template badges only make sense for org-wide rows (the template never
  // generates unit-scoped ones), so they show in the Global / All Scopes views.
  const showTemplateState = selectedUnitId === null || selectedUnitId === ALL_SCOPES

  const handleResetToTemplate = async (competency: Competency) => {
    try {
      setResettingCompetencyId(competency.id)
      const r = await mappingTemplateAPI.reset(positionId, competency.id)
      toast.success(t('templateResetDone', { level: r.level }))
      await fetchData()
    } catch (error: any) {
      toast.error(error?.response?.data?.error ?? t('templateResetError'))
      console.error(error)
    } finally {
      setResettingCompetencyId(null)
    }
  }

  const handleAdd = (competency: Competency) => {
    if (selectedUnitId === ALL_SCOPES) {
      toast.error(t('selectScopeToAddError'))
      return
    }
    setSelectedCompetency(competency)
    setSelectedPositionCompetency(null)
    setEditMode(false)
    setIsLevelDialogOpen(true)
  }

  const handleEdit = (competency: Competency, positionCompetency: PositionCompetency) => {
    setSelectedCompetency(competency)
    setSelectedPositionCompetency(positionCompetency)
    setEditMode(true)
    setIsLevelDialogOpen(true)
  }

  const handleView = (competency: Competency, positionCompetency?: PositionCompetency) => {
    setSelectedCompetency(competency)
    setSelectedPositionCompetency(positionCompetency || null)
    setIsViewDialogOpen(true)
  }

  const handleDelete = (positionCompetency: PositionCompetency) => {
    // The delete dialog names selectedCompetency: without this it showed
    // whichever competency was last edited or viewed.
    setSelectedCompetency(allCompetencies.find((c) => c.id === positionCompetency.competencyId) ?? positionCompetency.competency ?? null)
    setSelectedPositionCompetency(positionCompetency)
    setIsDeleteDialogOpen(true)
  }

  const handleLevelSubmit = async (level: number) => {
    try {
      if (editMode && selectedPositionCompetency) {
        await positionCompetencyAPI.update(selectedPositionCompetency.id, {
          level,
        })
        toast.success(t('levelUpdated'))
      } else {
        await positionCompetencyAPI.create({
          positionId,
          competencyId: selectedCompetency!.id,
          unitId: selectedUnitId,
          level,
        })
        toast.success(t('competencyAdded'))
      }
      await fetchData()
    } catch (error) {
      toast.error(t('saveError'))
      console.error(error)
    }
  }

  const handleDeleteConfirm = async () => {
    try {
      await positionCompetencyAPI.delete(selectedPositionCompetency!.id)
      toast.success(t('competencyRemoved'))
      await fetchData()
    } catch (error) {
      toast.error(t('removeError'))
      console.error(error)
    }
  }

  const toggleSelection = (id: string) => {
    setSelectedIds(prev =>
      prev.includes(id) ? prev.filter(i => i !== id) : [...prev, id]
    )
  }

  const toggleCompetencySelection = (id: string) => {
    setSelectedCompetencyIds(prev =>
      prev.includes(id) ? prev.filter(i => i !== id) : [...prev, id]
    )
  }

  const toggleSelectAll = (competencies: Array<{ positionCompetency?: PositionCompetency }>) => {
    const assignedIds = competencies
      .filter(c => c.positionCompetency)
      .map(c => c.positionCompetency!.id)
    
    if (selectedIds.length === assignedIds.length) {
      setSelectedIds([])
    } else {
      setSelectedIds(assignedIds)
    }
  }

  const toggleSelectAllNotAdded = (competencies: Array<{ competency: Competency; positionCompetency?: PositionCompetency }>) => {
    const notAddedIds = competencies
      .filter(c => !c.positionCompetency)
      .map(c => c.competency.id)
    
    if (selectedCompetencyIds.length === notAddedIds.length) {
      setSelectedCompetencyIds([])
    } else {
      setSelectedCompetencyIds(notAddedIds)
    }
  }

  const handleBulkDelete = async () => {
    if (selectedIds.length === 0) {
      toast.error(t('noCompetenciesSelected'))
      return
    }

    const templateSelected = positionCompetencies.filter((pc) => selectedIds.includes(pc.id) && pc.source === 'TEMPLATE').length
    const message = (selectedIds.length === 1 ? t('confirmRemoveSingle') : t('confirmRemoveMultiple', { count: selectedIds.length }))
      + (templateSelected > 0 ? '\n\n' + t('templateBulkRemoveNote', { count: templateSelected }) : '')
    if (!confirm(message)) {
      return
    }

    try {
      setIsBulkDeleting(true)
      await Promise.all(
        selectedIds.map(id => positionCompetencyAPI.delete(id))
      )
      toast.success(selectedIds.length === 1 ? t('removedSingle') : t('removedMultiple', { count: selectedIds.length }))
      setSelectedIds([])
      await fetchData()
    } catch (error) {
      toast.error(t('removeError'))
      console.error(error)
    } finally {
      setIsBulkDeleting(false)
    }
  }

  const handleBulkAdd = async () => {
    if (selectedCompetencyIds.length === 0) {
      toast.error(t('noCompetenciesSelected'))
      return
    }
    if (selectedUnitId === ALL_SCOPES) {
      toast.error(t('selectScopeToAddError'))
      return
    }

    setIsBulkLevelDialogOpen(true)
  }

  const handleBulkAddConfirm = async (level: number) => {
    try {
      setIsBulkAdding(true)
      await Promise.all(
        selectedCompetencyIds.map(competencyId =>
          positionCompetencyAPI.create({
            positionId,
            competencyId,
            unitId: selectedUnitId,
            level,
          })
        )
      )
      toast.success(t('addedWithLevel', { count: selectedCompetencyIds.length, level }))
      setSelectedCompetencyIds([])
      setIsBulkLevelDialogOpen(false)
      await fetchData()
    } catch (error) {
      toast.error(t('addError'))
      console.error(error)
    } finally {
      setIsBulkAdding(false)
    }
  }

  // A mapping row whose competency was deleted from the master list keeps
  // pointing at nothing (competencyId null) — it still counts toward the
  // row total but never shows up in groupCompetenciesByCluster() since that
  // walks allCompetencies, not positionCompetencies. Surface it separately
  // instead of letting it inflate the "assigned" count silently.
  const orphanedPositionCompetencies = positionCompetencies.filter((pc) => !pc.competencyId)
  const orphanedPositionCompetencyCount = orphanedPositionCompetencies.length
  // Distinct competencies, not raw rows — matches the listing page's count
  // (also deduped by competencyId) even in "All Scopes" mode, where the same
  // competency could in principle have both a Global and a unit-scoped row.
  const validPositionCompetencyCount = new Set(
    positionCompetencies.filter((pc) => pc.competencyId).map((pc) => pc.competencyId)
  ).size

  const handleRemoveOrphaned = async () => {
    if (orphanedPositionCompetencies.length === 0) return
    if (!confirm(t('confirmRemoveOrphaned', { count: orphanedPositionCompetencies.length }))) {
      return
    }

    try {
      setIsRemovingOrphaned(true)
      await Promise.all(orphanedPositionCompetencies.map((pc) => positionCompetencyAPI.delete(pc.id)))
      toast.success(t('orphanedMappingsRemoved'))
      await fetchData()
    } catch (error) {
      toast.error(t('removeError'))
      console.error(error)
    } finally {
      setIsRemovingOrphaned(false)
    }
  }

  const groupedCompetencies = groupCompetenciesByCluster()

  if (isLoading) {
    return (
      <div className="space-y-4">
        <Skeleton className="h-12 w-full" />
        <Skeleton className="h-64 w-full" />
      </div>
    )
  }

  return (
    <div className="space-y-4">
      <div className="flex items-center gap-4">
        <Button
          variant="ghost"
          size="sm"
          onClick={() => router.push("/admin/position-competencies")}
        >
          <IconArrowLeft className="mr-2 size-4" />
          {t('backToPositions')}
        </Button>
      </div>

      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h1 className="text-3xl font-bold text-primary">{position?.name}</h1>
          <p className="text-muted-foreground ">
            {position?.grade?.name && `${t('gradeLabel', { grade: position.grade.name })} • `}
            {validPositionCompetencyCount === 1
              ? t('statusAssignedSingle', { count: validPositionCompetencyCount })
              : t('statusAssignedMultiple', { count: validPositionCompetencyCount })}
            {orphanedPositionCompetencyCount > 0 && (
              <span className="text-destructive"> {t('orphanedInlineNote', { count: orphanedPositionCompetencyCount })}</span>
            )}
          </p>
        </div>

        {featureFlags.unitScopedCompetency && (
          <div className="flex flex-col gap-1 sm:items-end">
            <div className="flex items-center gap-2">
              <span className="text-sm text-muted-foreground">{t('unitScopeLabel')}:</span>
              <Popover open={unitScopePopoverOpen} onOpenChange={setUnitScopePopoverOpen}>
                <PopoverTrigger asChild>
                  <Button
                    variant="outline"
                    role="combobox"
                    aria-expanded={unitScopePopoverOpen}
                    className="w-full justify-between sm:w-[220px]"
                  >
                    <span className="flex items-center gap-2 truncate">
                      <IconBuilding className="size-4 shrink-0 opacity-50" />
                      {selectedUnitId === ALL_SCOPES
                        ? t('unitScopeAll')
                        : selectedUnitId
                        ? units.find((u) => u.id === selectedUnitId)?.name ?? t('unitScopeGlobal')
                        : t('unitScopeGlobal')}
                    </span>
                  </Button>
                </PopoverTrigger>
                <PopoverContent className="w-[260px] p-0">
                  <Command>
                    <CommandInput placeholder={t('unitScopeSearchPlaceholder')} />
                    <CommandList className="max-h-[260px] overflow-y-auto">
                      <CommandEmpty>{t('unitScopeEmptyText')}</CommandEmpty>
                      <CommandGroup>
                        <CommandItem
                          key="all"
                          value={t('unitScopeAll')}
                          onSelect={() => {
                            setSelectedUnitId(ALL_SCOPES)
                            setUnitScopePopoverOpen(false)
                          }}
                        >
                          {t('unitScopeAll')}
                        </CommandItem>
                        <CommandItem
                          key="global"
                          value={t('unitScopeGlobal')}
                          onSelect={() => {
                            setSelectedUnitId(null)
                            setUnitScopePopoverOpen(false)
                          }}
                        >
                          {t('unitScopeGlobal')}
                        </CommandItem>
                        {units.map((unit) => (
                          <CommandItem
                            key={unit.id}
                            value={unit.name}
                            onSelect={() => {
                              setSelectedUnitId(unit.id)
                              setUnitScopePopoverOpen(false)
                            }}
                          >
                            {unit.name}
                          </CommandItem>
                        ))}
                      </CommandGroup>
                    </CommandList>
                  </Command>
                </PopoverContent>
              </Popover>
            </div>
            <p className="max-w-[260px] text-right text-xs text-muted-foreground">
              {selectedUnitId === ALL_SCOPES ? t('unitScopeAllHelperText') : t('unitScopeHelperText')}
            </p>
          </div>
        )}
      </div>

      {scopeSummary && selectedUnitId === null && (
        <Alert>
          <IconInfoCircle />
          <AlertTitle>{t('globalNoticeTitle', { global: scopeSummary.globalCount })}</AlertTitle>
          <AlertDescription>
            {t('globalNoticeBody', { units: scopeSummary.unitCount, range: perStaffRange })}
          </AlertDescription>
        </Alert>
      )}

      {scopeSummary && selectedUnitId === ALL_SCOPES && (
        <Alert>
          <IconInfoCircle />
          <AlertTitle>{t('allScopesNoticeTitle')}</AlertTitle>
          <AlertDescription>
            {t('allScopesNoticeBody', {
              total: validPositionCompetencyCount,
              global: scopeSummary.globalCount,
              units: scopeSummary.unitCount,
              range: perStaffRange,
            })}
          </AlertDescription>
        </Alert>
      )}

      {unitEffective && (
        <Alert>
          <IconInfoCircle />
          <AlertTitle>
            {t('unitEffectiveNoticeTitle', {
              unit: units.find((u) => u.id === selectedUnitId)?.name ?? '',
              total: unitEffective.total,
            })}
          </AlertTitle>
          <AlertDescription>
            {t('unitEffectiveNoticeBody', { global: unitEffective.global, scoped: unitEffective.scoped })}
          </AlertDescription>
        </Alert>
      )}

      {orphanedPositionCompetencyCount > 0 && (
        <Card className="border-destructive/50 bg-destructive/5">
          <CardContent className="flex items-center justify-between gap-4 py-4">
            <div className="flex items-center gap-2 text-sm">
              <IconAlertTriangle className="size-4 text-destructive shrink-0" />
              <span>
                {orphanedPositionCompetencyCount === 1
                  ? t('orphanedWarningSingle', { count: orphanedPositionCompetencyCount })
                  : t('orphanedWarningMultiple', { count: orphanedPositionCompetencyCount })}
              </span>
            </div>
            <Button
              variant="destructive"
              size="sm"
              onClick={handleRemoveOrphaned}
              disabled={isRemovingOrphaned}
            >
              <IconTrashX className="mr-2 size-4" />
              {orphanedPositionCompetencyCount === 1
                ? t('removeDeletedMappingSingle')
                : t('removeDeletedMappingMultiple')}
            </Button>
          </CardContent>
        </Card>
      )}

      <Tabs value={activeTab} onValueChange={setActiveTab} className="w-full">
        <div className="flex gap-4">
          <div className="w-64 space-y-4">
            <div className="relative">
              <IconSearch className="absolute left-2.5 top-2.5 size-4 text-muted-foreground" />
              <Input
                placeholder={t('searchPlaceholder')}
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                className="pl-8"
              />
            </div>
            <TabsList className="flex flex-col h-fit w-full">
              {Object.entries(groupedCompetencies).map(([clusterId, { cluster, competencies }]) => (
                <TabsTrigger key={clusterId} value={clusterId} className="justify-start gap-3 w-full">
                  {cluster?.color && (
                    <div
                      className="size-4 rounded shrink-0"
                      style={{ backgroundColor: cluster.color }}
                    />
                  )}
                  <span className="flex-1 text-left truncate">{cluster?.name || t('uncategorized')}</span>
                  <Badge className="ml-auto">
                    {competencies.filter((c) => c.positionCompetency).length}/{competencies.length}
                  </Badge>
                </TabsTrigger>
              ))}
            </TabsList>
          </div>

          <div className="flex-1">
            {Object.entries(groupedCompetencies).map(([clusterId, { cluster, competencies }]) => (
              <TabsContent key={clusterId} value={clusterId} className="mt-0">
            <Card>
              <CardHeader>
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-2">
                    {cluster?.color && (
                      <div
                        className="size-4 rounded"
                        style={{ backgroundColor: cluster.color }}
                      />
                    )}
                    <CardTitle>{cluster?.name || t('uncategorized')}</CardTitle>
                    <Badge>
                      {competencies.filter((c) => c.positionCompetency).length} / {competencies.length}
                    </Badge>
                  </div>
                  <div className="flex items-center gap-2">
                    {selectedCompetencyIds.length > 0 && (
                      <Button
                        variant="default"
                        size="sm"
                        onClick={handleBulkAdd}
                        disabled={isBulkAdding || selectedUnitId === ALL_SCOPES}
                        title={selectedUnitId === ALL_SCOPES ? t('selectScopeToAddTooltip') : undefined}
                      >
                        <IconPlus className="mr-2 size-4" />
                        {t('addSelected', { count: selectedCompetencyIds.length })}
                      </Button>
                    )}
                    {selectedIds.length > 0 && (
                      <Button
                        variant="destructive"
                        size="sm"
                        onClick={handleBulkDelete}
                        disabled={isBulkDeleting}
                      >
                        <IconTrashX className="mr-2 size-4" />
                        {t('deleteSelected', { count: selectedIds.length })}
                      </Button>
                    )}
                  </div>
                </div>
                <CardDescription>
                  {t('assignedCount', { count: competencies.filter((c) => c.positionCompetency).length })}
                  {(() => {
                    const info = templateFor(competencies[0]?.competency)
                    if (info.level === null) return null
                    return <span className="block text-xs">{info.covered ? t('templateClusterCovered', { level: info.level }) : t('templateClusterSuggested', { level: info.level })}</span>
                  })()}
                </CardDescription>
              </CardHeader>
              <CardContent>
                {(competencies.filter(c => !c.positionCompetency).length > 0 || competencies.filter(c => c.positionCompetency).length > 0) && (
                  <div className="mb-3 flex items-center gap-6 border-b pb-2">
                    {competencies.filter(c => !c.positionCompetency).length > 0 && (
                      <div className="flex items-center gap-2">
                        <Checkbox
                          checked={
                            competencies.filter(c => !c.positionCompetency).length > 0 &&
                            selectedCompetencyIds.length === competencies.filter(c => !c.positionCompetency).length
                          }
                          onCheckedChange={() => toggleSelectAllNotAdded(competencies)}
                        />
                        <span className="text-sm text-muted-foreground">
                          {t('selectAllNotAdded')}
                        </span>
                      </div>
                    )}
                    {competencies.filter(c => c.positionCompetency).length > 0 && (
                      <div className="flex items-center gap-2">
                        <Checkbox
                          checked={
                            competencies.filter(c => c.positionCompetency).length > 0 &&
                            selectedIds.length === competencies.filter(c => c.positionCompetency).length
                          }
                          onCheckedChange={() => toggleSelectAll(competencies)}
                        />
                        <span className="text-sm text-muted-foreground">
                          {t('selectAllAssigned')}
                        </span>
                      </div>
                    )}
                  </div>
                )}
                <div className="space-y-2">
                  {competencies.map(({ competency, positionCompetency }) => (
                    <div
                      key={competency.id}
                      className="flex items-center justify-between rounded-lg border p-3 hover:bg-muted/50"
                    >
                      <div className="flex items-center gap-3">
                        {positionCompetency ? (
                          <Checkbox
                            checked={selectedIds.includes(positionCompetency.id)}
                            onCheckedChange={() => toggleSelection(positionCompetency.id)}
                          />
                        ) : (
                          <Checkbox
                            checked={selectedCompetencyIds.includes(competency.id)}
                            onCheckedChange={() => toggleCompetencySelection(competency.id)}
                          />
                        )}
                        {positionCompetency ? (
                          <Badge variant="default">{t('badgeAdded')}</Badge>
                        ) : (
                          <Badge variant="outline">{t('badgeNotAdded')}</Badge>
                        )}
                        {showTemplateState && positionCompetency && !positionCompetency.unitId && positionCompetency.source === 'TEMPLATE' && (
                          <Badge variant="secondary" title={t('templateBadgeHint')}>{t('templateBadge')}</Badge>
                        )}
                        {showTemplateState && positionCompetency && !positionCompetency.unitId && positionCompetency.source !== 'TEMPLATE' && templateFor(competency).covered && (
                          <Badge variant="outline" className="border-amber-500 text-amber-700 dark:text-amber-400" title={t('overriddenBadgeHint', { level: templateFor(competency).level ?? '-' })}>
                            {t('overriddenBadge')}
                          </Badge>
                        )}
                        {showTemplateState && !positionCompetency && excludedCompetencyIds.has(competency.id) && (
                          <Badge variant="outline" className="border-dashed" title={t('excludedBadgeHint')}>{t('excludedBadge')}</Badge>
                        )}
                        <div>
                          <div className="flex items-center gap-2">
                            <p className="font-medium">{competency.name}</p>
                            {selectedUnitId === ALL_SCOPES && positionCompetency && (
                              <Badge variant="outline" className="text-xs">
                                {positionCompetency.unitId
                                  ? positionCompetency.unit?.name ?? t('unitScopeGlobal')
                                  : t('unitScopeBadgeGlobal')}
                              </Badge>
                            )}
                          </div>
                          {positionCompetency && (
                            <p className="text-sm text-muted-foreground">
                              {t('requiredLevel', { level: positionCompetency.level })}
                            </p>
                          )}
                        </div>
                      </div>
                      <div className="flex items-center gap-2">
                        {showTemplateState && templateFor(competency).covered && (
                          (positionCompetency && !positionCompetency.unitId && positionCompetency.source !== 'TEMPLATE') ||
                          (!positionCompetency && excludedCompetencyIds.has(competency.id))
                        ) && (
                          <Button
                            variant="ghost"
                            size="sm"
                            onClick={() => handleResetToTemplate(competency)}
                            disabled={resettingCompetencyId === competency.id}
                            title={t('resetToTemplateHint', { level: templateFor(competency).level ?? '-' })}
                          >
                            <IconRestore className="size-4" />
                            <span className="sr-only">{t('resetToTemplate')}</span>
                          </Button>
                        )}
                        {positionCompetency ? (
                          <>
                            <Button
                              variant="ghost"
                              size="sm"
                              onClick={() => handleEdit(competency, positionCompetency)}
                            >
                              <IconEdit className="size-4" />
                            </Button>
                            <Button
                              variant="ghost"
                              size="sm"
                              onClick={() => handleDelete(positionCompetency)}
                            >
                              <IconTrash className="size-4" />
                            </Button>
                          </>
                        ) : (
                          <Button
                            variant="outline"
                            size="sm"
                            onClick={() => handleAdd(competency)}
                            disabled={selectedUnitId === ALL_SCOPES}
                            title={selectedUnitId === ALL_SCOPES ? t('selectScopeToAddTooltip') : undefined}
                          >
                            <IconPlus className="mr-2 size-4" />
                            {t('actionAdd')}
                          </Button>
                        )}
                      </div>
                    </div>
                  ))}
                </div>
              </CardContent>
            </Card>
              </TabsContent>
            ))}
          </div>
        </div>
      </Tabs>      <CompetencyLevelDialog
        open={isLevelDialogOpen}
        onOpenChange={setIsLevelDialogOpen}
        competency={selectedCompetency}
        currentLevel={selectedPositionCompetency?.level}
        isEdit={editMode}
        onSubmit={handleLevelSubmit}
        suggestedLevel={templateFor(selectedCompetency).level}
        notice={editMode && selectedPositionCompetency?.source === 'TEMPLATE' ? t('templateEditNotice') : null}
      />

      <CompetencyViewDialog
        open={isViewDialogOpen}
        onOpenChange={setIsViewDialogOpen}
        competency={selectedCompetency}
        positionCompetency={selectedPositionCompetency}
      />

      <CompetencyDeleteDialog
        open={isDeleteDialogOpen}
        onOpenChange={setIsDeleteDialogOpen}
        competency={selectedCompetency}
        onConfirm={handleDeleteConfirm}
        notice={selectedPositionCompetency?.source === 'TEMPLATE' && !selectedPositionCompetency.unitId ? t('templateDeleteNotice') : null}
      />

      <BulkLevelDialog
        open={isBulkLevelDialogOpen}
        onOpenChange={setIsBulkLevelDialogOpen}
        count={selectedCompetencyIds.length}
        isLoading={isBulkAdding}
        onSubmit={handleBulkAddConfirm}
        suggestedLevel={(() => {
          const levels = new Set(selectedCompetencyIds.map((id) => templateFor(allCompetencies.find((c) => c.id === id)).level))
          return levels.size === 1 ? [...levels][0] : null
        })()}
      />
    </div>
  )
}
